// Package tunnel fronts the panel behind another server.
//
// The exit servers in internal/relay change where a customer appears to be.
// This changes where they connect: a machine in a country the customer can
// reach accepts their connection and carries it to the panel. The panel keeps
// serving the same inbounds on the same ports; only the address customers are
// given changes.
//
// Backhaul's two sides are not symmetrical, and getting them the wrong way
// round produces a tunnel that never connects rather than one that connects
// badly. The machine customers reach — the near one, in the country being
// fronted — runs the SERVER: it binds the tunnel port and opens the
// customer-facing ports. The panel runs the CLIENT: it dials out. That is the
// point of a reverse tunnel, and it is why the panel can sit on a network
// nobody can reach from outside.
package tunnel

import (
	"fmt"
	"net"
	"sort"
	"strconv"
	"strings"
)

// Transport is how the tunnel carries its traffic, named as the tools name
// them, so an operator reading their documentation finds what they expect;
// only udpovertcp is the panel's own (see onBackhaul).
//
// Which one is fastest is not a question with a general answer, and it was
// measured once already: on a path with no loss the tunnel ran at 97% of the
// raw link whatever the transport, so a transport change bought nothing. It
// is offered because a network that blocks one may pass another, not as a
// speed control.
type Transport string

const (
	TransportTCP     Transport = "tcp"
	TransportTCPMux  Transport = "tcpmux"
	TransportUDP     Transport = "udp"
	TransportWS      Transport = "ws"
	TransportWSMux   Transport = "wsmux"
	TransportWSS     Transport = "wss"
	TransportWSSMux  Transport = "wssmux"
	TransportUDPoTCP Transport = "udpovertcp"
)

// onBackhaul is the name Backhaul's config takes: udpovertcp is tcp there, and
// the server adds accept_udp for it.
func (t Transport) onBackhaul() Transport {
	if t == TransportUDPoTCP {
		return TransportTCP
	}
	return t
}

var transports = map[Transport]bool{
	TransportTCP: true, TransportTCPMux: true, TransportUDP: true,
	TransportWS: true, TransportWSMux: true, TransportWSS: true,
	TransportWSSMux: true, TransportUDPoTCP: true,
}

// ValidTransport refuses a transport Backhaul does not know. A config naming
// one is rejected by the binary at startup, which shows up as a tunnel that
// will not come up for no visible reason.
func ValidTransport(t Transport) error {
	if t == "" {
		return fmt.Errorf("no transport chosen")
	}
	if !transports[t] {
		return fmt.Errorf("%q is not a transport Backhaul knows", t)
	}
	return nil
}

// Pair is one tunnel: a front machine and the panel behind it.
type Pair struct {
	// Id is the panel's own identifier for this tunnel, used for the file and
	// unit names so two tunnels cannot share either.
	Id int
	// FrontAddress is the machine customers connect to.
	FrontAddress string
	// TunnelPort is where the front listens for the panel to dial in. Not a
	// customer-facing port: nothing but the panel should ever reach it.
	TunnelPort int
	// Transport carries the tunnel.
	Transport Transport
	// Tool is the program carrying it. Empty is Backhaul.
	Tool Tool
	// Leg is empty for a tunnel's main leg and LegUDP for Backhaul's second
	// one. Set by Legs, never by hand.
	Leg string
	// Token authenticates the two ends to each other. Both sides must carry
	// the same one, and a tunnel with an empty token accepts anybody who
	// finds the port. Backhaul's UDP leg carries one derived from it.
	Token string
	// Ports are the customer-facing ports the front opens and forwards to the
	// panel. Mirrored rather than remapped: a customer's existing profile
	// keeps working with nothing changed but the address.
	Ports []int
	// ProxyPorts are ports whose service expects a PROXY v2 header naming the
	// customer; Legs moves them onto BackPack's proxy leg.
	ProxyPorts []int
	// ProxyProtocol is set by Legs on the leg that sends that header.
	ProxyProtocol bool
}

// ServerConfig is what runs on the front machine — the one customers reach.
func ServerConfig(p Pair) (string, error) {
	if err := p.validate(); err != nil {
		return "", err
	}
	if p.Tool.norm() == ToolBackPack {
		return backpackServerConfig(p), nil
	}
	var b strings.Builder
	w := func(format string, args ...any) { fmt.Fprintf(&b, format+"\n", args...) }

	w("# generated by x-ui for tunnel %s — edits are overwritten", p.Key())
	w("[server]")
	// 0.0.0.0 rather than the front's own address: a machine that learns its
	// address from DHCP, or has several, would bind nothing on a restart.
	w("bind_addr = \"0.0.0.0:%d\"", p.TunnelPort)
	w("transport = %q", string(p.Transport.onBackhaul()))
	if p.Transport == TransportUDPoTCP {
		w("accept_udp = true")
	}
	w("token = %q", p.Token)
	if p.needsTLSPair() {
		// Provisioning puts the pair there before the leg starts.
		w("tls_cert = %q", p.remoteCertPath())
		w("tls_key = %q", p.remoteKeyPath())
	}
	w("keepalive_period = 75")
	w("heartbeat = 40")
	// The customer-facing ports. Each forwards to the same number on the far
	// side of the tunnel, which is the panel's own listener.
	w("ports = [")
	for _, port := range normalisePorts(p.Ports, p.TunnelPort) {
		w("    \"%d=127.0.0.1:%d\",", port, port)
	}
	w("]")
	return b.String(), nil
}

// ClientConfig is what runs on the panel's own machine. It dials out, which
// is the whole reason this works from a network that accepts no incoming
// connection of its own.
func ClientConfig(p Pair) (string, error) {
	if err := p.validate(); err != nil {
		return "", err
	}
	if p.Tool.norm() == ToolBackPack {
		return backpackClientConfig(p), nil
	}
	var b strings.Builder
	w := func(format string, args ...any) { fmt.Fprintf(&b, format+"\n", args...) }

	w("# generated by x-ui for tunnel %s — edits are overwritten", p.Key())
	w("[client]")
	w("remote_addr = %q", net.JoinHostPort(strings.TrimSpace(p.FrontAddress), strconv.Itoa(p.TunnelPort)))
	w("transport = %q", string(p.Transport.onBackhaul()))
	w("token = %q", p.Token)
	w("connection_pool = 8")
	w("dial_timeout = 10")
	// A front that reboots must be dialled again without anybody noticing,
	// so the client retries rather than exiting.
	w("retry_interval = 3")
	w("keepalive_period = 75")
	w("heartbeat = 40")
	return b.String(), nil
}

func (p Pair) validate() error {
	if p.Id <= 0 {
		return fmt.Errorf("a tunnel needs an id, so its files cannot collide with another's")
	}
	if strings.TrimSpace(p.FrontAddress) == "" {
		return fmt.Errorf("no address for the panel to dial")
	}
	if p.TunnelPort <= 0 || p.TunnelPort > 65535 {
		return fmt.Errorf("tunnel port %d is not a port", p.TunnelPort)
	}
	if err := ValidTransportFor(p.Tool, p.Transport); err != nil {
		return err
	}
	// An empty token is not a convenience: the tunnel port is open to the
	// internet, and without one anybody who finds it is inside.
	if strings.TrimSpace(p.Token) == "" {
		return fmt.Errorf("no token, so anyone who finds the tunnel port is inside it")
	}
	if len(normalisePorts(p.Ports, p.TunnelPort)) == 0 {
		return fmt.Errorf("no ports to forward, so the tunnel would carry nothing")
	}
	return nil
}

// normalisePorts drops anything that is not a port and anything repeated, in
// order. A duplicate makes Backhaul bind the same port twice and fail to
// start, which reads as a tunnel that is simply down.
// The tunnel's own port is excluded along with the rest: forwarding it would
// have the front take the panel's dial-in and send it back down the tunnel it
// arrived on.
func normalisePorts(ports []int, tunnelPort int) []int {
	seen := make(map[int]bool, len(ports))
	out := make([]int, 0, len(ports))
	for _, port := range ports {
		if port <= 0 || port > 65535 || port == tunnelPort || seen[port] {
			continue
		}
		seen[port] = true
		out = append(out, port)
	}
	sort.Ints(out)
	return out
}

// UnitName is the systemd unit on the front machine.
//
// Named after this tunnel and nothing else. The first version of this idea,
// in another project, wrote one fixed name and one fixed path: standing up a
// second tunnel overwrote the first one's config, restarted over its unit,
// and took it down. The id is in the name so that cannot happen, and so
// restarting one tunnel leaves every other alone.
func UnitName(id int) string { return "backhaul-x-ui-" + strconv.Itoa(id) }

// RemoteConfigPath is where that unit reads its config on the front machine.
func RemoteConfigPath(id int) string {
	return "/etc/backhaul/x-ui-" + strconv.Itoa(id) + ".toml"
}
