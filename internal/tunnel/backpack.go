// BackPackRelease is the BackPack version the panel installs, pinned for the
// reason Release is: two ends set up months apart must run the same binary.
const BackPackRelease = "v1.8.5"

// backpackSigningKey is BackPack's release-signing key, base64 of the raw 32
// bytes, the same one its own updater carries (internal/app.ReleasePublicKey
// upstream). A SHA256SUMS that this key did not sign is refused, and with it
// every archive the list describes.
const backpackSigningKey = "uDVeC9NUFceAuhg53ZWbBNTVSaMC8tEvtwWmcDZmV9Q="

// backpackSigningKeyOverride lets a test sign its own fake release.
var backpackSigningKeyOverride string

// backpackReleaseBase is where releases are fetched from; a test points it at
// a local server.
var backpackReleaseBase = "https://github.com/AminMGMT/BackPack/releases/download/"

// backpackBinaryName is what the panel installs BackPack as, on the front and
// on its own machine. Not "backpack": an operator may run BackPack's own
// tunnels beside the panel's, from /usr/local/bin/backpack, and the panel must
// never swap that binary under them.
const backpackBinaryName = "x-ui-backpack"

// backpackServerConfig is the front's end. UDP is forwarded on the same
// tunnel, so every inbound — WireGuard, Hysteria, TUIC, cisco's DTLS — reaches
// the panel without a second one.
func backpackServerConfig(p Pair) string {
	var b strings.Builder
	w := func(format string, args ...any) { fmt.Fprintf(&b, format+"\n", args...) }
	w("# generated by x-ui for tunnel %s — edits are overwritten", p.Key())
	w("[server]")
	w("bind_addr = \"0.0.0.0:%d\"", p.TunnelPort)
	w("transport = %q", string(p.Transport))
	w("token = %q", p.Token)
	w("keepalive_period = 75")
	w("heartbeat = 40")
	w("nodelay = true")
	w("accept_udp = true")
	if p.ProxyProtocol {
		// TCP only: UDP flows arrive bare, which is what ocserv's DTLS wants.
		w("proxy_protocol = true")
	}
	w("log_level = \"info\"")
	w("ports = [")
	for _, port := range normalisePorts(p.Ports, p.TunnelPort) {
		w("    \"%d=127.0.0.1:%d\",", port, port)
	}
	w("]")
	return b.String()
}

// backpackClientConfig is the panel's end. skip_optz keeps BackPack from
// applying its system-wide socket and sysctl tuning on the panel's machine:
// that machine runs the VPN servers and possibly other tunnels, and a tunnel
// client has no business retuning it every time it starts.
func backpackClientConfig(p Pair) string {
	var b strings.Builder
	w := func(format string, args ...any) { fmt.Fprintf(&b, format+"\n", args...) }
	w("# generated by x-ui for tunnel %s — edits are overwritten", p.Key())
	w("[client]")
	w("remote_addr = %q", net.JoinHostPort(strings.TrimSpace(p.FrontAddress), strconv.Itoa(p.TunnelPort)))
	w("transport = %q", string(p.Transport))
	w("token = %q", p.Token)
	w("connection_pool = 8")
	w("dial_timeout = 10")
	// A front that reboots must be dialled again without anybody noticing.
	w("retry_interval = 3")
	w("keepalive_period = 75")
	w("nodelay = true")
	w("skip_optz = true")
	w("log_level = \"info\"")
	return b.String()
}

// backpackArchive is the release asset for one architecture.
func backpackArchive(arch string) string {
	return "backpack_linux_" + arch + ".tar.gz"
}

// verifyBackPackRelease checks the list of checksums against the signing key.
// What is signed is the tag and the list together, "backpack release <tag>",
// a newline, then the list: a signature over the list alone would let a mirror
// serve an older release's genuine files under a newer tag.
func verifyBackPackRelease(tag string, sums, sig []byte, key ed25519.PublicKey) error {
	raw, err := base64.StdEncoding.DecodeString(strings.TrimSpace(string(sig)))
	if err != nil {
		return fmt.Errorf("the BackPack release signature is not base64: %w", err)
	}
	msg := append([]byte("backpack release "+tag+"\n"), sums...)
	if len(raw) != ed25519.SignatureSize || !ed25519.Verify(key, msg, raw) {
		return fmt.Errorf("the BackPack %s checksums are not signed by BackPack's release key; refusing to install", tag)
	}
	return nil
}

// sumFor finds one file's checksum in a SHA256SUMS list.
func sumFor(sums []byte, file string) (string, error) {
	sc := bufio.NewScanner(bytes.NewReader(sums))
	for sc.Scan() {
		f := strings.Fields(sc.Text())
		if len(f) == 2 && strings.TrimPrefix(f[1], "*") == file {
			return strings.ToLower(f[0]), nil
		}
	}
	return "", fmt.Errorf("%s is not in the release's checksum list", file)
}

// extractBinary pulls one regular file, by base name, out of a .tar.gz.
func extractBinary(tgz []byte, name string) ([]byte, error) {
	gz, err := gzip.NewReader(bytes.NewReader(tgz))
	if err != nil {
		return nil, fmt.Errorf("the BackPack archive is not gzip: %w", err)
	}
	defer gz.Close()
	tr := tar.NewReader(gz)
	for {
		hdr, err := tr.Next()
		if errors.Is(err, io.EOF) {
			return nil, fmt.Errorf("the BackPack archive holds no %s", name)
		}
		if err != nil {
			return nil, fmt.Errorf("the BackPack archive is damaged: %w", err)
		}
		if hdr.Typeflag == tar.TypeReg && path.Base(hdr.Name) == name {
			// A binary is tens of megabytes; anything past 256 MiB is not one.
			return io.ReadAll(io.LimitReader(tr, 256<<20))
		}
	}
}

// backpackCacheDir is where verified binaries are kept on the panel's machine.
var backpackCacheDirOverride string

func backpackCacheDir() string {
	if backpackCacheDirOverride != "" {
		return backpackCacheDirOverride
	}
	return filepath.Join(config.GetDBFolderPath(), "tools", "backpack-"+BackPackRelease)
}

var backpackFetchMu sync.Mutex

// FetchBackPack returns the path of a verified BackPack binary for arch,
// downloading it once. The panel fetches and checks it itself and then pushes
// it to the front, rather than having the front fetch it: a front in Iran may
// not reach GitHub at all, and the check then happens where the signing key
// is, on a machine the operator already trusts.
func FetchBackPack(ctx context.Context, arch string) (string, error) {
	backpackFetchMu.Lock()
	defer backpackFetchMu.Unlock()

	dir := backpackCacheDir()
	bin := filepath.Join(dir, backpackBinaryName+"-linux-"+arch)
	if info, err := os.Stat(bin); err == nil && info.Mode().IsRegular() && info.Size() > 0 {
		return bin, nil
	}

	pinned := backpackSigningKey
	if backpackSigningKeyOverride != "" {
		pinned = backpackSigningKeyOverride
	}
	key, err := base64.StdEncoding.DecodeString(pinned)
	if err != nil || len(key) != ed25519.PublicKeySize {
		return "", errors.New("the pinned BackPack signing key is malformed")
	}
	base := backpackReleaseBase + BackPackRelease + "/"
	sums, err := download(ctx, base+"SHA256SUMS", 1<<20)
	if err != nil {
		return "", err
	}
	sig, err := download(ctx, base+"SHA256SUMS.sig", 4<<10)
	if err != nil {
		return "", err
	}
	if err := verifyBackPackRelease(BackPackRelease, sums, sig, ed25519.PublicKey(key)); err != nil {
		return "", err
	}
	file := backpackArchive(arch)
	want, err := sumFor(sums, file)
	if err != nil {
		return "", err
	}
	tgz, err := download(ctx, base+file, 128<<20)
	if err != nil {
		return "", err
	}
	got := sha256.Sum256(tgz)
	if hex.EncodeToString(got[:]) != want {
		return "", fmt.Errorf("the downloaded %s does not match its signed checksum; refusing to install", file)
	}
	data, err := extractBinary(tgz, "backpack")
	if err != nil {
		return "", err
	}
	if err := os.MkdirAll(dir, 0o750); err != nil {
		return "", fmt.Errorf("could not make %s: %w", dir, err)
	}
	tmp := bin + ".part"
	if err := os.WriteFile(tmp, data, 0o755); err != nil {
		return "", fmt.Errorf("could not write %s: %w", bin, err)
	}
	if err := os.Rename(tmp, bin); err != nil {
		_ = os.Remove(tmp)
		return "", fmt.Errorf("could not put %s in place: %w", bin, err)
	}
	return bin, nil
}

// download fetches a URL into memory, capped so a misbehaving server cannot
// fill the panel's memory.
func download(ctx context.Context, url string, limit int64) ([]byte, error) {
	ctx, cancel := context.WithTimeout(ctx, 3*time.Minute)
	defer cancel()
	req, err := http.NewRequestWithContext(ctx, http.MethodGet, url, nil)
	if err != nil {
		return nil, err
	}
	resp, err := http.DefaultClient.Do(req)
	if err != nil {
		return nil, fmt.Errorf("could not download %s: %w", url, err)
	}
	defer resp.Body.Close()
	if resp.StatusCode != http.StatusOK {
		return nil, fmt.Errorf("could not download %s: %s", url, resp.Status)
	}
	data, err := io.ReadAll(io.LimitReader(resp.Body, limit+1))
	if err != nil {
		return nil, fmt.Errorf("could not download %s: %w", url, err)
	}
	if int64(len(data)) > limit {
		return nil, fmt.Errorf("%s is larger than it should be", url)
	}
	return data, nil
}
